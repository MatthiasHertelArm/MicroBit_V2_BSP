#include "microbit_v2.h"

static const uint32_t mb_row_pin[5] = { MB_PIN_ROW1, MB_PIN_ROW2, MB_PIN_ROW3, MB_PIN_ROW4, MB_PIN_ROW5 };
static const uint32_t mb_col_pin[5] = { MB_PIN_COL1, MB_PIN_COL2, MB_PIN_COL3, MB_PIN_COL4, MB_PIN_COL5 };

static volatile uint8_t mb_fb[5];           /* one byte per row, bit 4 = column 0 (left) */
static volatile uint32_t mb_row;

