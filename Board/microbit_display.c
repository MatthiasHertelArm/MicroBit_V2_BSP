const uint8_t *microbit_display_font (char c) {
  if ((c >= 'a') && (c <= 'z')) {
    c = (char)(c - 'a' + 'A');
  }
  if ((c < ' ') || (c > 'Z')) {
    c = '?';
  }
  return mb_font[(uint32_t)c - 32U];
}

static void mb_display_drive_row (uint32_t row) {
  uint32_t c;
  uint8_t bits = mb_fb[row];

  for (c = 0U; c < 5U; c++) {
    if ((bits & (0x10U >> c)) != 0U) {
      mb_gpio_clear(mb_col_pin[c]);                    /* LED on */
    } else {
      mb_gpio_set(mb_col_pin[c]);
    }
  }
  mb_gpio_set(mb_row_pin[row]);
}

void TIMER1_IRQHandler (void) {
  if (NRF_TIMER1->EVENTS_COMPARE[0] != 0U) {
    NRF_TIMER1->EVENTS_COMPARE[0] = 0U;
    mb_gpio_clear(mb_row_pin[mb_row]);                 /* previous row off */
    mb_row = (mb_row + 1U) % 5U;
    mb_display_drive_row(mb_row);
  }
}

void microbit_display_init (void) {
  uint32_t n;

  for (n = 0U; n < 5U; n++) {
    mb_fb[n] = 0U;
    mb_gpio_output(mb_row_pin[n], 0U, false);
    mb_gpio_output(mb_col_pin[n], 1U, false);
  }
  mb_row = 0U;

  NRF_TIMER1->TASKS_STOP  = 1U;
  NRF_TIMER1->TASKS_CLEAR = 1U;
  NRF_TIMER1->MODE      = TIMER_MODE_MODE_Timer << TIMER_MODE_MODE_Pos;
  NRF_TIMER1->BITMODE   = TIMER_BITMODE_BITMODE_16Bit << TIMER_BITMODE_BITMODE_Pos;
  NRF_TIMER1->PRESCALER = 4U;                                       /* 16 MHz / 16 = 1 MHz */
  NRF_TIMER1->CC[0]     = 1000U;                                    /* 1 ms per row */
  NRF_TIMER1->SHORTS    = TIMER_SHORTS_COMPARE0_CLEAR_Msk;
  NRF_TIMER1->EVENTS_COMPARE[0] = 0U;
  NRF_TIMER1->INTENSET  = TIMER_INTENSET_COMPARE0_Msk;
  NVIC_SetPriority(TIMER1_IRQn, 2U);
  NVIC_EnableIRQ(TIMER1_IRQn);
  NRF_TIMER1->TASKS_START = 1U;
}

void microbit_display_off (void) {
  uint32_t n;

  NRF_TIMER1->TASKS_STOP = 1U;
  NRF_TIMER1->INTENCLR   = TIMER_INTENCLR_COMPARE0_Msk;
  NVIC_DisableIRQ(TIMER1_IRQn);
  for (n = 0U; n < 5U; n++) {
    mb_gpio_clear(mb_row_pin[n]);
    mb_gpio_set(mb_col_pin[n]);
  }
}

void microbit_display_clear (void) {
  uint32_t n;
  for (n = 0U; n < 5U; n++) {
    mb_fb[n] = 0U;
  }
}

void microbit_display_set_pixel (uint32_t x, uint32_t y, bool on) {
  if ((x > 4U) || (y > 4U)) {
    return;
  }
  if (on) {
    mb_fb[y] |= (uint8_t)(0x10U >> x);
  } else {
    mb_fb[y] &= (uint8_t)~(0x10U >> x);
  }
}

bool microbit_display_get_pixel (uint32_t x, uint32_t y) {
  if ((x > 4U) || (y > 4U)) {
    return false;
  }
  return ((mb_fb[y] & (0x10U >> x)) != 0U);
}

void microbit_display_show_image (const uint8_t rows[5]) {
  uint32_t n;
  for (n = 0U; n < 5U; n++) {
    mb_fb[n] = rows[n] & 0x1FU;
  }
}

void microbit_display_show_char (char c) {
  microbit_display_show_image(microbit_display_font(c));
}
